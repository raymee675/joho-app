import { writeFileSync } from 'node:fs';
const K = [
 ['あはれなり','哀れなり','しみじみとした趣がある'],['をかし','','趣がある・かわいらしい'],['いと','','たいそう・とても'],['うつくし','美し','かわいらしい'],
 ['ありがたし','有り難し','めったにない'],['あさまし','浅まし','驚きあきれるほどだ'],['やがて','','すぐに・そのまま'],['つとめて','','早朝・翌朝'],
 ['いみじ','','はなはだしい・すばらしい'],['おどろく','驚く','はっと気づく・目を覚ます'],['ゆかし','','見たい・知りたい'],['なでふ','','どうして・なんという'],
 ['かなし','悲し・愛し','いとしい・悲しい'],['めでたし','愛でたし','すばらしい'],['わろし','悪し','よくない'],['ねんず','念ず','我慢する・祈る'],
 ['あやし','怪し','不思議だ・身分が低い'],['いたづらなり','徒なり','むなしい・無駄だ'],['すさまじ','','興ざめだ'],['つれづれなり','徒然なり','することがなくて退屈だ'],
 ['のたまふ','宣ふ','おっしゃる'],['おぼす','思す','お思いになる'],['まゐる','参る','参上する・差し上げる'],['さぶらふ','候ふ','お仕えする・あります'],['心にくし','','奥ゆかしい'],
];
const B = [
 ['以','もって','〜によって・〜を用いて'],['於','おいて','〜に・〜で・〜より'],['而','しかうして','そして・しかし'],['故','ゆゑ','理由・だから'],
 ['蓋','けだし','思うに'],['嘗','かつて','以前・かつて'],['遂','つひに','とうとう'],['寧','むしろ','いっそ'],
 ['豈','あに','どうして〜か'],['雖','いへども','〜ではあるが'],['又','また','さらに'],['即','すなはち','すぐに・つまり'],
 ['須','すべからく','ぜひ〜すべきだ'],['盍','なんぞ〜ざる','どうして〜しないのか'],['未','いまだ〜ず','まだ〜ない'],
];
const mk = (deck, list, per) => list.map(([w, k, m], i) => ({
  id: `${deck}-${i + 1}`, deck, chapterId: `${deck}-ch${Math.floor(i / per) + 1}`, no: i + 1,
  word: w, kanji: k || null, reading: null, pos: null,
  senses: [{ label: null, meanings: m.split('・') }], notes: [],
}));
const items = [...mk('kobun', K, 10), ...mk('kanbun', B, 8)];
const chapters = [];
for (const deck of ['kobun', 'kanbun']) {
  const ids = [...new Set(items.filter((i) => i.deck === deck).map((i) => i.chapterId))];
  for (const id of ids) chapters.push({ id, deck, title: `${deck === 'kobun' ? '古文単語' : '漢文'} ${id.split('ch')[1]}`, itemIds: items.filter((i) => i.chapterId === id).map((i) => i.id) });
}
writeFileSync('sample/deck.json', JSON.stringify({ version: 'sample', items, chapters }, null, 1));
console.log(items.length, chapters.length);
